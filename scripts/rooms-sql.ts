// Writes supabase/sql/50-rooms.sql from the game's own catalogue (src/game/residence.ts), so the server checks the
// same buildings, blocks, categories and capacities the signup offers. Run: npx --yes tsx scripts/rooms-sql.ts
import { writeFileSync } from 'node:fs';
import { CATEGORIES, RESIDENCES } from '../src/game/residence';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const buildings = RESIDENCES.map((r) => `  (${q(r.id)}, ${q(r.catalogue)}, ${r.blocks ? `array[${r.blocks.map((b) => q(b.id)).join(', ')}]` : 'null'})`).join(',\n');
const categories = CATEGORIES.filter((c) => !c.unresolved).map((c) => `  (${q(c.id)}, ${q(c.catalogue)}, ${c.capacity}, ${c.blocks ? `array[${c.blocks.map(q).join(', ')}]` : 'null'})`).join(',\n');

const sql = `-- LEGONRUSH rooms: hall and hostel room places and roommates (the walking and accommodation feature).
-- Run after supabase/schema.sql. Safe to run again. Generated by scripts/rooms-sql.ts from src/game/residence.ts:
-- regenerate it when the catalogue changes.
--
-- A player's place is one row: building, block, category, room and bed. claim_room() keeps the place of a player who
-- chose the same thing before (signing in again never reshuffles), otherwise puts them in a random room of that
-- building, block and exact category that has a free bed (so compatible players share), or opens a new room when all
-- are full. A per-building lock and the keys (one row per bed, one place per player) make simultaneous claims safe: a
-- room never holds more than its capacity. Beds with no player are shown by the game as NPC roommates. Nobody reads the
-- table directly: room_roster() shows a player their own room only.

-- ---------- the catalogue the server checks against ----------
create table if not exists public.room_buildings (
  id text primary key check (id ~ '^[a-z0-9-]{2,30}$'),
  catalogue text not null,
  blocks text[]
);
create table if not exists public.room_categories (
  id text primary key check (id ~ '^[a-z0-9-]{2,30}$'),
  catalogue text not null,
  capacity smallint not null check (capacity between 1 and 12),
  blocks text[]
);
insert into public.room_buildings (id, catalogue, blocks) values
${buildings}
on conflict (id) do update set catalogue = excluded.catalogue, blocks = excluded.blocks;
insert into public.room_categories (id, catalogue, capacity, blocks) values
${categories}
on conflict (id) do update set catalogue = excluded.catalogue, capacity = excluded.capacity, blocks = excluded.blocks;
alter table public.room_buildings enable row level security;
alter table public.room_categories enable row level security;
drop policy if exists "catalogue readable" on public.room_buildings;
create policy "catalogue readable" on public.room_buildings for select using (true);
drop policy if exists "catalogue readable" on public.room_categories;
create policy "catalogue readable" on public.room_categories for select using (true);

-- ---------- places ----------
create table if not exists public.room_places (
  building text not null references public.room_buildings on delete cascade,
  block text not null default '',
  room text not null check (room ~ '^[A-Z0-9]{2,12}$'),
  bed smallint not null check (bed between 0 and 11),
  category text not null references public.room_categories on delete cascade,
  user_id uuid not null unique references auth.users on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (building, block, room, bed)
);
create index if not exists room_places_pool on public.room_places (building, block, category, room);
alter table public.room_places enable row level security;
-- (no policies: only the functions below read or write places)

-- the room number's letters: the block's letters, else the building's initials (as the game's own allocate())
create or replace function public.room_prefix(p_building text, p_block text) returns text
language sql immutable set search_path = public as $$
  select coalesce(nullif(left(upper(regexp_replace(coalesce(p_block, ''), '[^A-Za-z]', '', 'g')), 2), ''),
                  nullif((select string_agg(upper(left(w, 1)), '') from regexp_split_to_table(p_building, '-') as w), ''), 'R');
$$;

-- claims (or keeps) the caller's place; returns the room, bed and capacity
create or replace function public.claim_room(p_building text, p_block text, p_category text)
returns table (room text, bed smallint, capacity smallint)
language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  blk text := coalesce(p_block, '');
  cap smallint;
  mine public.room_places;
  v_room text;
  v_bed smallint;
  tries int := 0;
begin
  if uid is null then raise exception 'sign in first'; end if;
  select c.capacity into cap
  from public.room_categories c join public.room_buildings b on b.id = p_building and b.catalogue = c.catalogue
  where c.id = p_category
    and ((b.blocks is null and blk = '') or (b.blocks is not null and blk = any(b.blocks)))
    and (c.blocks is null or b.blocks is null or blk = any(c.blocks));
  if cap is null then raise exception 'that room type is not offered there'; end if;
  -- the same choice as before: the same room and bed (no reshuffle on sign-in, reload or entering the room)
  select * into mine from public.room_places p where p.user_id = uid;
  if found and mine.building = p_building and mine.block = blk and mine.category = p_category then
    return query select mine.room, mine.bed, cap; return;
  end if;
  -- one claim at a time per building (concurrent sign-ups cannot overfill a room)
  perform pg_advisory_xact_lock(hashtext('legonrush-room:' || p_building));
  -- a changed choice gives up the old place
  delete from public.room_places p where p.user_id = uid;
  -- a random room of this exact category with a free bed
  select x.room into v_room from (
    select p.room from public.room_places p
    where p.building = p_building and p.block = blk and p.category = p_category
    group by p.room having count(*) < cap
  ) x order by random() limit 1;
  if v_room is null then
    -- all full (or none yet): a new room, numbered like the game's rooms (floor 1-3, rooms 01-36), unused in the building
    loop
      tries := tries + 1;
      v_room := public.room_prefix(p_building, blk) || (1 + floor(random() * 3))::int || lpad((1 + floor(random() * 36))::int::text, 2, '0');
      exit when not exists (select 1 from public.room_places p where p.building = p_building and p.block = blk and p.room = v_room);
      if tries > 400 then
        v_room := public.room_prefix(p_building, blk) || (4 + floor(random() * 6))::int || lpad((1 + floor(random() * 99))::int::text, 2, '0');
        exit when not exists (select 1 from public.room_places p where p.building = p_building and p.block = blk and p.room = v_room);
      end if;
      if tries > 2000 then raise exception 'no free room'; end if;
    end loop;
  end if;
  select min(g)::smallint into v_bed from generate_series(0, cap - 1) as g
  where not exists (select 1 from public.room_places p where p.building = p_building and p.block = blk and p.room = v_room and p.bed = g);
  insert into public.room_places (building, block, room, bed, category, user_id) values (p_building, blk, v_room, v_bed, p_category, uid);
  return query select v_room, v_bed, cap;
end;
$$;
grant execute on function public.claim_room(text, text, text) to authenticated;

-- the caller's own room: every place taken in it (the other beds are the game's NPC roommates)
create or replace function public.room_roster()
returns table (building text, block text, room text, category text, capacity smallint, bed smallint, user_id uuid, name text, look jsonb, you boolean)
language sql stable security definer set search_path = public as $$
  select p.building, p.block, p.room, p.category, c.capacity, p.bed, p.user_id, coalesce(pr.name, 'Resident'), pr.look, p.user_id = auth.uid()
  from public.room_places me
  join public.room_places p on p.building = me.building and p.block = me.block and p.room = me.room
  join public.room_categories c on c.id = p.category
  left join public.profiles pr on pr.id = p.user_id
  where me.user_id = auth.uid()
  order by p.bed;
$$;
grant execute on function public.room_roster() to authenticated;

-- gives up the caller's place (choosing "I don't stay in a hall or hostel"); signing out does not
create or replace function public.leave_room() returns void
language sql security definer set search_path = public as $$
  delete from public.room_places where user_id = auth.uid();
$$;
grant execute on function public.leave_room() to authenticated;
`;
writeFileSync(new URL('../supabase/sql/50-rooms.sql', import.meta.url), sql);
console.log('wrote supabase/sql/50-rooms.sql', CATEGORIES.length, 'categories,', RESIDENCES.length, 'buildings');
